// [proc,enum_var]

function enum_var(intArg0: stat): number {
    if (intArg0 == 20) {
        return varc_runecraftxp;
    }

    if (intArg0 == 12) {
        return varc_craftingxp;
    }

    if (intArg0 == 9) {
        return varc_fletchingxp;
    }

    if (intArg0 == 7) {
        return varc_cookingxp;
    }

    if (intArg0 == 22) {
        return varc_constructionxp;
    }

    if (intArg0 == 15) {
        return varc_herblorexp;
    }

    if (intArg0 == 6) {
        return varc_magicxp;
    }

    if (intArg0 == 13) {
        return varc_smithingxp;
    }

    if (intArg0 == 19) {
        return varc_farmingxp;
    }
    return 0;
}
